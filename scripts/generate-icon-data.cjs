#!/usr/bin/env node
/**
 * Regenerates src/components/Icon/icon-data.generated.ts from the cleaned
 * SVG assets in src/components/Icon/svgs/{regular,bold}/*.svg.
 *
 * Run this after adding, removing, or editing icon SVGs:
 *   node scripts/generate-icon-data.js
 *
 * Each source SVG is expected to already be in "cleaned" form (see the
 * Icon component's README/task notes): a single root <svg viewBox="..."
 * fill="currentColor" ...> wrapping one or more inner elements, with no
 * hardcoded hex fills and no width/height on the root tag.
 */
const fs = require('fs');
const path = require('path');

const ICON_DIR = path.join(__dirname, '..', 'src', 'components', 'Icon');
const SVGS_DIR = path.join(ICON_DIR, 'svgs');
const OUT_FILE = path.join(ICON_DIR, 'icon-data.generated.ts');
const VARIANTS = ['regular', 'bold'];

function esc(s) {
  return s.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
}

function extractViewBoxAndInner(svgSource) {
  const openMatch = svgSource.match(/<svg\b[^>]*>/);
  if (!openMatch) throw new Error('No <svg> tag found');
  const openTag = openMatch[0];
  const viewBoxMatch = openTag.match(/viewBox="([^"]*)"/);
  if (!viewBoxMatch) throw new Error('No viewBox found on root <svg>');
  const viewBox = viewBoxMatch[1];

  const afterOpen = svgSource.slice(openMatch.index + openTag.length);
  const closeIdx = afterOpen.lastIndexOf('</svg>');
  const innerSvg = afterOpen.slice(0, closeIdx).trim();

  return { viewBox, innerSvg };
}

const registry = {};
const errors = [];

for (const variant of VARIANTS) {
  const dir = path.join(SVGS_DIR, variant);
  if (!fs.existsSync(dir)) continue;
  for (const file of fs.readdirSync(dir)) {
    if (!file.endsWith('.svg')) continue;
    const name = file.replace(/\.svg$/, '');
    const source = fs.readFileSync(path.join(dir, file), 'utf8');
    try {
      const { viewBox, innerSvg } = extractViewBoxAndInner(source);
      if (!registry[name]) registry[name] = {};
      registry[name][variant] = { viewBox, innerSvg };
    } catch (e) {
      errors.push(`${variant}/${file}: ${e.message}`);
    }
  }
}

const names = Object.keys(registry).sort();

let out = '';
out += '// This file is generated by scripts/generate-icon-data.js — do not edit by hand.\n';
out += '// Run the script again after adding/updating SVGs in src/components/Icon/svgs/.\n\n';
out += `export type IconName =\n  | ${names.map((n) => `'${n}'`).join('\n  | ')};\n\n`;
out += `export type IconVariant = 'regular' | 'bold';\n\n`;
out += `export interface IconDef {\n  viewBox: string;\n  innerSvg: string;\n}\n\n`;
out += `export const iconRegistry: Record<IconName, Partial<Record<IconVariant, IconDef>>> = {\n`;

for (const name of names) {
  const variants = registry[name];
  out += `  '${name}': {\n`;
  for (const variant of VARIANTS) {
    if (variants[variant]) {
      const { viewBox, innerSvg } = variants[variant];
      out += `    ${variant}: { viewBox: '${viewBox}', innerSvg: \`${esc(innerSvg)}\` },\n`;
    }
  }
  out += `  },\n`;
}
out += `};\n`;

fs.writeFileSync(OUT_FILE, out, 'utf8');

console.log(`Wrote ${path.relative(process.cwd(), OUT_FILE)}`);
console.log(`Total icon names: ${names.length}`);
if (errors.length) {
  console.log('Errors:');
  errors.forEach((e) => console.log(' - ' + e));
  process.exitCode = 1;
}
